test("Battlefield 2 readiness matches rank, character progression, and ability caps",()=>{
 assert.equal(warTierDefaultForRanks([9,9,9]),"silver");
 assert.equal(warTierDefaultForRanks([12,12,12]),"gold");
 assert.equal(warTierDefaultForRanks([12,9,12]),"silver");
 assert.equal(warTierAbilityCap("silver"),26);
 assert.equal(warTierAbilityCap("gold"),35);
 assert.equal(warTierProgressionCap("silver"),8);
 assert.equal(warTierProgressionCap("gold"),11);
 assert.equal(warTierProgressionMet(8,"silver"),true);
 assert.equal(warTierProgressionMet(11,"silver"),true);
 assert.equal(warTierProgressionMet(7,"silver"),false);
 assert.equal(warTierProgressionMet(11,"gold"),true);
});
