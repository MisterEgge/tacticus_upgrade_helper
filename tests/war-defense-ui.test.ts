import assert from "node:assert/strict";
import test from "node:test";
import {createElement} from "react";
import {JSDOM} from "jsdom";
import WarDefensePlanner from "../app/war-defense/WarDefensePlanner";
import {WAR_PLAN_STORAGE_KEY} from "../src/domain/warBadgeTargets";
import {deploymentKey} from "../src/domain/warDeployment";

test("defense presents five-character assignments and persists owned machine choices independently of offense",async suite=>{
 const dom=new JSDOM("<html><body></body></html>",{url:"http://localhost/"});
 const descriptors=new Map<string,PropertyDescriptor|undefined>();
 for(const key of ["window","self","document","navigator","HTMLElement","Node","Event","MutationObserver","localStorage"]){descriptors.set(key,Object.getOwnPropertyDescriptor(globalThis,key));Object.defineProperty(globalThis,key,{configurable:true,value:dom.window[key as keyof typeof dom.window]});}
 const {render,fireEvent,cleanup,act,within}=await import("@testing-library/react");
 suite.after(async()=>{await act(async()=>cleanup());dom.window.close();for(const [key,descriptor] of descriptors){if(descriptor)Object.defineProperty(globalThis,key,descriptor);else Reflect.deleteProperty(globalThis,key);}});
 const team={name:"A / B / C / D / E",tier:"gold" as const,core:["A","B","C"],flex:[{id:"D",used:100,wins:95},{id:"E",used:80,wins:70}],used:200,wins:180,fieldable:true,missing:[],evidence:"core-flex" as const,members:["A","B","C","D","E"].map(name=>({id:name,name,icon:undefined,rank:12,activeLevel:35,passiveLevel:35,items:[]}))};
 const other={...team,name:"F / G / H / I / J",tier:"silver" as const,members:team.members.map((member,index)=>({...member,id:String(index+5),name:String(index+5)}))};
 const props={teams:[team,other],offenseTeams:[],machines:[{id:"tyranBiovore",name:"Biovore",active:17,passive:23}]};
 let view=render(createElement(WarDefensePlanner,props));
 assert.ok(view.getByText(/^Battlefield 2/));
 const group=within(view.getByRole("region",{name:team.name}));
 assert.equal(group.queryAllByRole("table").length,0);
 assert.equal(group.getAllByRole("listitem").length,5);
 assert.equal(group.getAllByRole("link").filter(link=>link.getAttribute("href")?.startsWith("/characters/")).length,5);
 assert.equal(group.queryByText("Flex choices"),null);
 fireEvent.click(group.getByRole("button",{name:"Edit order"}));
 fireEvent.click(group.getByRole("button",{name:"Move B earlier"}));
 const orderKey=deploymentKey(team.members.map(member=>member.id));
 assert.deepEqual(JSON.parse(localStorage.getItem(WAR_PLAN_STORAGE_KEY)!).defenseOrders[orderKey],["B","A","C","D","E"]);
 const machine=group.getByLabelText(team.name+" Machine of War");
 assert.equal(machine.querySelectorAll("option").length,2);
 fireEvent.change(machine,{target:{value:"tyranBiovore"}});
 assert.equal(JSON.parse(localStorage.getItem(WAR_PLAN_STORAGE_KEY)!).defenseMachines[team.name],"tyranBiovore");
 assert.equal(view.getByLabelText(other.name+" Machine of War").querySelector<HTMLOptionElement>('option[value="tyranBiovore"]')!.disabled,true);
 fireEvent.click(view.getByRole("button",{name:"Offense teams"}));
 assert.ok(view.getByText("0 distinct offense teams"));
 view.unmount();
 view=render(createElement(WarDefensePlanner,props));
 fireEvent.click(view.getByRole("button",{name:"Defense teams"}));
 assert.equal((view.getByLabelText(team.name+" Machine of War") as HTMLSelectElement).value,"tyranBiovore");
 const restored=within(view.getByRole("region",{name:team.name}));
 assert.equal(restored.getAllByRole("listitem")[0]!.textContent?.includes("B"),true);
 fireEvent.click(restored.getByRole("button",{name:"Reset order"}));
 assert.deepEqual(JSON.parse(localStorage.getItem(WAR_PLAN_STORAGE_KEY)!).defenseOrders[orderKey],["A","B","C","D","E"]);
 assert.equal((view.getByLabelText(team.name+" Machine of War") as HTMLSelectElement).value,"tyranBiovore");
 assert.equal(view.queryByText(/RESERVE/),null);
 view.unmount();
 localStorage.clear();
 view=render(createElement(WarDefensePlanner,{...props,machines:[...props.machines,{id:"blackForgefiend",name:"Forgefiend",active:1,passive:12}]}));
 fireEvent.click(view.getByRole("button",{name:"Fill unassigned machines"}));
 const assignments=JSON.parse(localStorage.getItem(WAR_PLAN_STORAGE_KEY)!).defenseMachines;
 assert.equal(Object.keys(assignments).length,2);
 assert.equal(new Set(Object.values(assignments)).size,2);
 assert.equal(view.queryByRole("button",{name:"Fill unassigned machines"}),null);
 fireEvent.change(view.getByLabelText(team.name+" Machine of War"),{target:{value:""}});
 const suggestion=within(view.getByRole("region",{name:team.name})).getByRole("button",{name:/^Use /});
 fireEvent.click(suggestion);
 assert.deepEqual(JSON.parse(localStorage.getItem(WAR_PLAN_STORAGE_KEY)!).defenseMachines,assignments);
});
